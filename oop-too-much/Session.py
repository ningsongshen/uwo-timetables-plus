class Session(object):
    def __init__(self, name, section, component, class_nbr, days, start_time, end_time, location, instructor):
        this.name = name # Course name/code
        this.section = section # Course section
        this.component = component
        this.class_nbr = class_nbr
        this.days = days
        this.start_time = start_time
        this.end_time = end_time
        this.location = location
        this.instructor = instructor

    